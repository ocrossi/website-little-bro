// 10. SCROLL-SPY ACTIVE LINKS Highlight
class ScrollSpy {
  init() {
    const links = document.querySelectorAll('.nav-menu-links a, .mobile-dropdown-links a');
    const sections = document.querySelectorAll('section[id]');

    const observer = new IntersectionObserver((entries) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          const id = entry.target.getAttribute('id');
          links.forEach(link => {
            if (link.getAttribute('href') === `#${id}`) {
              link.classList.add('active');
            } else {
              link.classList.remove('active');
            }
          });

          // Soft replace Hash URL (Safely caught inside try-catch to prevent iframe Sandboxing restrictions)
          try {
            if (window.location.hash !== `#${id}`) {
              history.replaceState(null, null, `#${id}`);
            }
          } catch (e) {
            // Address bar manipulation is disabled inside sandbox
          }
        }
      });
    }, {
      rootMargin: '-30% 0px -60% 0px',
      threshold: 0
    });

    sections.forEach(sec => observer.observe(sec));
  }
}


