// 8. COOKIE BANNER AND MAP CONSENT FLOW
class CookieBanner {
  constructor() {
    this.banner = document.getElementById('cookie-banner');
    this.acceptBtn = document.getElementById('cookie-accept-btn');
    this.refuseBtn = document.getElementById('cookie-refuse-btn');
    this.mapPlaceholder = document.getElementById('map-placeholder');
    this.mapIframe = document.getElementById('google-map-iframe');
    this.activateMapBtn = document.getElementById('btn-activate-map');
  }

  init() {
    if (!this.banner) return;

    let consent = null;
    try {
      consent = localStorage.getItem('cookie_consent');
    } catch (e) {
      // Fallback if localStorage is disabled in iframe
    }

    if (consent === 'accepted') {
      this.injectMap();
    } else if (!consent) {
      setTimeout(() => {
        this.banner.classList.add('show');
      }, 600);
    }

    this.acceptBtn.addEventListener('click', () => this.accept());
    this.refuseBtn.addEventListener('click', () => this.refuse());
    if (this.activateMapBtn) {
      this.activateMapBtn.addEventListener('click', () => this.accept());
    }
  }

  accept() {
    try {
      localStorage.setItem('cookie_consent', 'accepted');
    } catch (e) {
      // Ignore write block in sandbox
    }
    this.banner.classList.remove('show');
    this.injectMap();
  }

  refuse() {
    try {
      localStorage.setItem('cookie_consent', 'refused');
    } catch (e) {
      // Ignore write block in sandbox
    }
    this.banner.classList.remove('show');
  }

  injectMap() {
    if (this.mapIframe) {
      this.mapIframe.src = this.mapIframe.getAttribute('data-src');
      this.mapIframe.classList.add('active');
      if (this.mapPlaceholder) {
        this.mapPlaceholder.style.display = 'none';
      }
    }
  }
}


